def val(s):
    return int(s, 2)


def pc(v):
    return bin(v).count("1")


def span(words):
    n = len(words[0])
    out = set()
    for coeffs in itertools.product([0, 1], repeat=len(words)):
        v = 0
        for c, w in zip(coeffs, words):
            if c:
                v ^= val(w)
        out.add(v)
    return out


def kernel(checks):
    n = len(checks[0])
    return {y for y in range(2**n) if all(pc(y & val(c)) % 2 == 0 for c in checks)}


def rank_of(strs):
    b = Q.XorBasis()
    return sum(1 for s in strs if b.add(val(s)))


def sym(s):
    """The symplectic vector of a Pauli string as one integer: x bits above z bits, place 1 the most significant of each half."""
    n = len(s)
    x = val("".join("1" if c in "XY" else "0" for c in s))
    z = val("".join("1" if c in "ZY" else "0" for c in s))
    return (x << n) | z, x, z


def sym_commute(a, b):
    _, x1, z1 = sym(a)
    _, x2, z2 = sym(b)
    return (pc(x1 & z2) + pc(z1 & x2)) % 2 == 0


def rank_sym(gens):
    b = Q.XorBasis()
    return sum(1 for g in gens if b.add(sym(g)[0]))


def stab_distance(gens):
    """Lightest Pauli that commutes with every generator and is not in their span (letters only): weights up to n, all positions, all letter choices."""
    n = len(gens[0])
    basis = Q.XorBasis()
    for g in gens:
        basis.add(sym(g)[0])
    for w in range(1, n + 1):
        for pos in itertools.combinations(range(n), w):
            for ls in itertools.product("XYZ", repeat=w):
                s = ["I"] * n
                for p, l in zip(pos, ls):
                    s[p] = l
                s = "".join(s)
                if all(sym_commute(s, g) for g in gens) and not basis.contains(sym(s)[0]):
                    return w
    return None


def lookup(gens, maxw):
    """syndrome -> lightest error, built by enumerating errors weight by weight in position-then-letter order."""
    n = len(gens[0])
    table = {tuple([0] * len(gens)): "I" * n}
    for w in range(1, maxw + 1):
        for pos in itertools.combinations(range(n), w):
            for ls in itertools.product("XYZ", repeat=w):
                s = ["I"] * n
                for p, l in zip(pos, ls):
                    s[p] = l
                s = "".join(s)
                syn = tuple(0 if sym_commute(s, g) else 1 for g in gens)
                table.setdefault(syn, s)
    return table


def corrected(gens, table, err):
    syn = tuple(0 if sym_commute(err, g) else 1 for g in gens)
    corr = table[syn]
    basis = Q.XorBasis()
    for g in gens:
        basis.add(sym(g)[0])
    return basis.contains(sym(err)[0] ^ sym(corr)[0])


def single(n, q, l):
    s = ["I"] * n
    s[q] = l
    return "".join(s)


def dense_gap(a, b):
    A, B = Q.pauli_matrix(a), Q.pauli_matrix(b)
    return float(np.max(np.abs(A @ B - B @ A)))


def group_size(mats):
    """The number of distinct matrices in the group generated by the given matrices (closure under products)."""
    found = [np.eye(mats[0].shape[0], dtype=complex)]
    frontier = list(found)
    while frontier:
        nxt = []
        for A in frontier:
            for G in mats:
                B = G @ A
                if not any(np.allclose(B, F) for F in found):
                    found.append(B)
                    nxt.append(B)
        frontier = nxt
    return len(found)


def projector(gens, signs):
    n = len(gens[0])
    P = np.eye(2**n, dtype=complex)
    for g, s in zip(gens, signs):
        P = P @ (np.eye(2**n) + s * Q.pauli_matrix(g)) / 2
    return P


