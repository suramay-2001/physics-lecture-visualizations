/**
 * Content-Security-Policy for the built site (owner: S; W-L1 §4.6, S-L1 §4b, decision #11).
 *
 *  - `cspMeta()` (Vite plugin, build only) injects `<meta http-equiv="Content-Security-Policy">` as the FIRST child
 *    of <head>, so it governs everything parsed after it. It is build-only because the dev server injects an
 *    inline React-refresh preamble that `script-src 'self'` would block.
 *  - `headersFile()` renders `public/_headers` (Netlify / Cloudflare Pages syntax) for a header-capable host: the
 *    same directives plus what a <meta> cannot carry (frame-ancestors, upgrade-insecure-requests) and the other
 *    security headers. `node build/headers.ts` rewrites the file; build/csp.security.test.ts fails on drift.
 *
 * What the runtime needs, and why nothing more is allowed (validated on the built app, S build round):
 *  - scripts: only Vite's external module chunks → `script-src 'self'` (no inline, no eval, no wasm, no blob:).
 *  - styles: bundled <link rel=stylesheet> → `style-src-elem 'self'`; KaTeX HTML (innerHTML) carries
 *    `style="…"` attributes → `style-src-attr 'unsafe-inline'`. React `style={}`, GSAP and drei <Html> write via
 *    CSSOM, which CSP does not govern. `style-src` is the CSP2 fallback for browsers without -elem/-attr.
 *  - fonts: self-hosted woff2 + one KaTeX woff Vite inlines as data: → `font-src 'self' data:`.
 *  - images/workers: three/drei textures and loaders may use data:/blob: → `img-src` / `worker-src` allow them.
 *  - network: `connect-src 'self'` is what makes "no runtime third party" fail closed (drei/troika/Babylon CDN
 *    defaults, analytics, remote HDRIs/GLBs).
 * Any exception (a CDN, 'unsafe-eval', 'wasm-unsafe-eval' for Draco/Meshopt, blob: scripts for drei <Text>)
 * is an interface change that needs S sign-off.
 */
import type { Plugin } from 'vite'

export const CSP: Readonly<Record<string, string>> = Object.freeze({
  'default-src': "'none'",
  'script-src': "'self'",
  'style-src': "'self' 'unsafe-inline'",
  'style-src-elem': "'self'",
  'style-src-attr': "'unsafe-inline'",
  'img-src': "'self' data: blob:",
  'font-src': "'self' data:",
  'connect-src': "'self'",
  'worker-src': "'self' blob:",
  'media-src': "'self'",
  'manifest-src': "'self'",
  'object-src': "'none'",
  'base-uri': "'none'",
  'form-action': "'none'",
})

/** Directive string. `headerOnly` adds what a <meta> tag cannot carry (frame-ancestors, upgrade-insecure-requests). */
export const cspString = (opts: { headerOnly?: boolean } = {}): string => {
  const parts = Object.entries(CSP).map(([k, v]) => `${k} ${v}`)
  if (opts.headerOnly) parts.push("frame-ancestors 'none'", 'upgrade-insecure-requests')
  return parts.join('; ')
}

/** Build-only CSP <meta> injector: first child of <head>. */
export function cspMeta(): Plugin {
  return {
    name: 'spin-lab:csp-meta',
    apply: 'build',
    transformIndexHtml: {
      order: 'post',
      handler: () => [{ tag: 'meta', attrs: { 'http-equiv': 'Content-Security-Policy', content: cspString() }, injectTo: 'head-prepend' }],
    },
  }
}

/** Response headers for every path on a header-capable static host (S-L1 §4b). */
export const SECURITY_HEADERS: Readonly<Record<string, string>> = Object.freeze({
  'Content-Security-Policy': cspString({ headerOnly: true }),
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  // (S-L1 §4b listed interest-cohort=(); FLoC is gone and Chrome logs "Unrecognized feature" for it, so
  // its successor browsing-topics is denied instead.)
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'X-Frame-Options': 'DENY',
})

/** Contents of `public/_headers` (Netlify / Cloudflare Pages). GitHub Pages ignores it; the meta tag is the floor. */
export function headersFile(): string {
  const lines = [
    '# GENERATED by app/build/headers.ts from app/build/csp.ts. Do not edit by hand: run `node build/headers.ts` in app/.',
    '# Netlify / Cloudflare Pages syntax. Hosts without header support get only the build-time CSP <meta> tag.',
    '/*',
    ...Object.entries(SECURITY_HEADERS).map(([k, v]) => `  ${k}: ${v}`),
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
  ]
  return lines.join('\n') + '\n'
}
