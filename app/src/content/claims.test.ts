describe('claims.json (numpy) ↔ engine (every lecture\'s values, content/values.ts)', () => {
  it('every engine value has a numpy twin, and no numpy key is stale', () => {
    expect(Object.keys(NUMPY).sort()).toEqual(Object.keys(V).sort())
  })
  it.each(Object.entries(V))('%s agrees with numpy', (key, value) => {
    expect(Math.abs(value - NUMPY[key]), `${key}: engine ${value} vs numpy ${NUMPY[key]}`).toBeLessThan(key === 'theta34' ? 1e-9 : 1e-12)
  })
})

describe('the number reader', () => {
  it('reads fractions, glyphs, 50/50, percentages and decimals; skips angles and references', () => {
    const got = shownNumbers('At 45°, $P(+) = \\tfrac{1}{2}$ or \\tfrac34; ⅛ + 50/50, 3/4, 25 %, ≈ 0.854 (§1.4, pp. 15–16, MIT 8.05, L1 p.4, Unit 2.5) $\\cos^2 22.5^\\circ$')
    expect(got.map((g) => g.raw.replace(/\s/g, ''))).toEqual(['\\tfrac{1}{2}', '\\tfrac34', '⅛', '50/50', '3/4', '25%', '0.854'])
    expect(got.map((g) => g.value)).toEqual([0.5, 0.75, 0.125, 0.5, 0.75, 0.25, 0.854])
  })
  it('ignores symbolic fractions', () => {
    expect(shownNumbers('$\\tfrac{1+\\cos\\theta}{2}$, $1/\\sqrt2$, $\\tfrac{\\hbar}{2}$, $2S_z/\\hbar$, ħ/2')).toEqual([])
  })
  it('the name "spin ½" is not a result, but a ½ beside it still is (L7 review)', () => {
    expect(shownNumbers('For a spin ½, a spin-½ ket and a spin-\\tfrac12 particle')).toEqual([])
    expect(shownNumbers('for a spin ½, $p_+ = \\tfrac12$ and ½').map((g) => g.value)).toEqual([0.5, 0.5])
  })
  it('a wrong number is caught (mutation: 0.854 → 0.845 in a copy of L1)', () => {
    const L = LECTURES.find((l) => l.id === 'L1')!
    const mutated: Lecture = {
      ...L,
      units: L.units.map((u) =>
        u.id !== 'l1-average' ? u : { ...u, story: u.story!.map((b) => (b.id === 'l1-average:b3' ? { ...b, caption: b.caption!.replace('0.854', '0.845') } : b)) },
      ),
    }
    expect(unbacked(mutated)).toEqual(['l1-average:b3 caption: 0.845'])
  })
})

/** The ledger's checks for one chapter in one track, against a table of twins. */
function ledger(lecture: Lecture, track: Track, twins: Readonly<Record<string, number>>) {
  it('every claim is keyed, and its key has a numpy value', () => {
    const bad = allClaims(lecture)
      .map(({ where, claim }) => ({ where, key: claimKey(claim), text: claim.text }))
      .filter((c) => c.key === null || !(c.key in twins))
    expect(bad).toEqual([])
  })
  it('every displayed decimal, fraction and percentage is backed by a claim of its beat or unit', () => {
    expect(unbacked(lecture, twins, track)).toEqual([])
  })
  it('no raw engine float reaches the page: no exponent notation, no number with 7 or more decimals', () => {
    // a template like `${V.x}` prints 1.232595164407831e-32 for a zero that is not exactly 0 (L2 review, 2026-09-27)
    const RAW = /\d(?:\.\d+)?e[-+]?\d|\d\.\d{7,}/
    const bad = readingOrder(lecture, track).filter((site) => RAW.test(site.text)).map((site) => `${site.where} ${site.field}: ${site.text.slice(0, 80)}`)
    expect(bad).toEqual([])
  })
  it('the reader finds numbers in every unit with a story or review (guard against a vacuous pass)', () => {
    for (const u of lecture.units.filter((x) => x.story?.length || x.review)) {
      const found = scopedSites({ ...lecture, units: [u] }, track).flatMap((s) => shownNumbers(s.text))
      expect(found.length, u.id).toBeGreaterThan(0)
    }
  })
}

describe.each(TRACKED)('claim ledger: %s', (_, lecture, track) => ledger(lecture, track, NUMPY))

describe.each(COURSES.qc709.tracks.map((t) => [t] as const))('claim ledger: the DEV demo chapter Q0, %s', (track) => {
  it('the analytic twins agree with the fixture’s engine values', () => {
    for (const [k, v] of Object.entries(Q0_VALUES)) expect(Math.abs(v - DEMO_TWINS[k]), k).toBeLessThan(1e-15)
  })
  ledger(Q0, track, DEMO_TWINS)
})

describe('the ledger reads each track (mutations of Q0)', () => {
  const b3 = Q0.units[0].story![2]
  const patch = (fn: (b: typeof b3) => typeof b3): Lecture => ({
    ...Q0,
    units: Q0.units.map((u, k) => (k ? u : { ...u, story: u.story!.map((b) => (b.id === b3.id ? fn(b) : b)) })),
  })
  it('a wrong number in the Formal text is caught in Formal only', () => {
    const bad = patch((b) => ({ ...b, formal: b.formal!.replace('\\tfrac12', '\\tfrac13') }))
    expect(unbacked(bad, DEMO_TWINS, 'formal')).toEqual(['q0-demo-sphere:b3 text: \\tfrac13'])
    expect(unbacked(bad, DEMO_TWINS, 'ground')).toEqual([])
  })
  it('a wrong number in a derivation line is caught in that line’s track', () => {
    const bad = patch((b) => ({ ...b, derivation: { ...b.derivation!, ground: b.derivation!.ground.map((s, i) => (i === 2 ? { ...s, why: 'So the chance is 0.4 here.' } : s)) } }))
    expect(unbacked(bad, DEMO_TWINS, 'ground')).toEqual(['q0-demo-sphere:b3.derivation.ground[2] why: 0.4'])
    expect(unbacked(bad, DEMO_TWINS, 'formal')).toEqual([])
  })
})
