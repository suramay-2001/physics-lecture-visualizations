/* ---------------------------------------------------------------------------------------------- */
/* Displayed numbers                                                                               */
/* ---------------------------------------------------------------------------------------------- */

export interface Shown {
  raw: string
  value: number
  /** Half a unit of the last shown digit (exact for fractions). */
  tol: number
}

const GLYPHS: Record<string, number> = { '½': 1 / 2, '¼': 1 / 4, '¾': 3 / 4, '⅛': 1 / 8, '⅜': 3 / 8, '⅓': 1 / 3, '⅔': 2 / 3 }
const EXACT = 1e-9

/** Decimals, fractions and percentages in a rich string (TeX included), in order of the rules below. */
export function shownNumbers(text: string): Shown[] {
  const out: Shown[] = []
  let s = text
  const eat = (re: RegExp, f: (m: RegExpMatchArray) => Shown | null) => {
    s = s.replace(re, (...args: unknown[]) => {
      const m = args.slice(0, -2) as unknown as RegExpMatchArray
      const r = f(m)
      if (r) out.push(r)
      return ' '
    })
  }
  // inputs and references, not results (a bridge `<<id|shown>>` names a place in Spin Lab, never a result)
  eat(/<<[^>|]+\|[^>]+>>/g, () => null)
  eat(/\d+(?:\.\d+)?\s*(?:°|\^\\circ|\^\{\\circ\})/g, () => null)
  eat(/(?:§|\bpp?\.\s?|\bFig\.\s?|\beqs?\.\s?|\bExps?\.\s?|\bProblem\s|\bDefinition\s|\bLecture\s|\bUnits?\s|\bMIT\s|\bL)\d+(?:[.–-]\d+)*/g, () => null)
  // the name of the spin ("spin ½", "spin-½") is not a result
  eat(/\bspin[- ](?:½|\\tfrac\{?1\}?\{?2\}?)/g, () => null)
  // exact forms
  eat(/\\[td]?frac\{?(\d+)\}?\{?(\d+)\}?/g, (m) => ({ raw: m[0], value: Number(m[1]) / Number(m[2]), tol: EXACT }))
  eat(/[½¼¾⅛⅜⅓⅔]/g, (m) => ({ raw: m[0], value: GLYPHS[m[0]], tol: EXACT }))
  eat(/\b50\/50\b/g, (m) => ({ raw: m[0], value: 0.5, tol: EXACT }))
  eat(/(?<![\d.])(\d+)\s*\/\s*(\d+)(?![\d.])/g, (m) => ({ raw: m[0], value: Number(m[1]) / Number(m[2]), tol: EXACT }))
  // rounded forms
  eat(/(?<![\d.])(\d+(?:\.(\d+))?)\s*\\?%/g, (m) => ({ raw: m[0], value: Number(m[1]) / 100, tol: 0.5 * 10 ** -((m[2]?.length ?? 0) + 2) + 1e-12 }))
  eat(/(?<![\d.])(\d+)\.(\d+)(?![\d.])/g, (m) => ({ raw: m[0], value: Number(`${m[1]}.${m[2]}`), tol: 0.5 * 10 ** -m[2].length + 1e-12 }))
  return out
}

/* ---------------------------------------------------------------------------------------------- */
/* Sites and the claims in scope                                                                   */
/* ---------------------------------------------------------------------------------------------- */

interface Scoped {
  where: string
  text: string
  claims: Claim[]
}

/**
 * The sites a track shows, each with the claims in its scope (the beat's, its reveal's and its unit's; a derivation
 * line adds its own). Per track (W-709-platform §B "Lints"): Formal reads the Formal texts and derivation, over the
 * same claims, so a number must be backed in both tracks.
 */
function scopedSites(l: Lecture, track: Track = 'ground'): Scoped[] {
  const out: Scoped[] = []
  for (const u of l.units) {
    const unitClaims = [...(u.claims ?? []), ...(u.review?.claims ?? [])]
    for (const raw of u.story ?? []) {
      const b = pickTrack(raw, track)
      const claims = [...(b.claims ?? []), ...(b.reveal?.claims ?? []), ...unitClaims]
      for (const [field, text] of [
        ['text', b.text],
        ['caption', b.caption],
        ['reveal.text', b.reveal?.text],
        ['reveal.caption', b.reveal?.caption],
      ] as const)
        if (text) out.push({ where: `${b.id} ${field}`, text, claims })
      if (b.derivation) out.push({ where: `${b.id}.derivation result`, text: `$${b.derivation.result}$`, claims })
      derivationSteps(b, track).forEach((s, i) => {
        const stepClaims = [...(s.claims ?? []), ...claims]
        out.push({ where: `${b.id}.derivation.${track}[${i}] why`, text: s.why, claims: stepClaims })
        out.push({ where: `${b.id}.derivation.${track}[${i}] tex`, text: `$${s.tex}$`, claims: stepClaims })
      })
    }
    if (u.review) {
      const card = pickReview(u.review, track)
      for (const [i, p] of card.points.entries()) out.push({ where: `${u.id}.review.points[${i}]`, text: p, claims: unitClaims })
      out.push({ where: `${u.id}.review.equations`, text: card.equations, claims: unitClaims })
      out.push({ where: `${u.id}.review.trap`, text: card.trap, claims: unitClaims })
    }
  }
  return out
}

function allClaims(l: Lecture): { where: string; claim: Claim }[] {
  return l.units.flatMap((u) => [
    ...(u.claims ?? []).map((claim) => ({ where: u.id, claim })),
    ...(u.review?.claims ?? []).map((claim) => ({ where: `${u.id}.review`, claim })),
    ...(u.story ?? []).flatMap((b) => [
      ...[...(b.claims ?? []), ...(b.reveal?.claims ?? [])].map((claim) => ({ where: b.id, claim })),
      ...(['ground', 'formal'] as const).flatMap((t) => derivationSteps(b, t).flatMap((s, i) => (s.claims ?? []).map((claim) => ({ where: `${b.id}.derivation.${t}[${i}]`, claim })))),
    ]),
  ])
}

/** Displayed numbers that no claim in scope backs, as "where: raw". */
function unbacked(l: Lecture, numpy: Readonly<Record<string, number>> = NUMPY, track: Track = 'ground'): string[] {
  const bad: string[] = []
  for (const site of scopedSites(l, track)) {
    const values = site.claims.map((c) => numpy[claimKey(c) ?? ''] ?? Number.NaN)
    for (const n of shownNumbers(site.text)) if (!values.some((v) => Math.abs(v - n.value) <= n.tol)) bad.push(`${site.where}: ${n.raw}`)
  }
  return bad
}

