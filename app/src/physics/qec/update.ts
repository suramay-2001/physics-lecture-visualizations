/**
 * The measurement update rule for stabilizer groups (Chapter B3, unit b3-logical-measure; Horsman et al. 2012 §3.1 uses it for the seam checks;
 * Aaronson & Gottesman, Phys. Rev. A 70, 052328 for the rule itself). Measuring a Hermitian Pauli P on the state stabilized by an independent,
 * commuting list of signed generators:
 *   1. some generator g anticommutes with P: the outcome is a fair coin; the FIRST such generator is replaced by (−1)^outcome · P, every other
 *      generator that anticommutes with P is multiplied by g (so it commutes with P again); the number of generators is unchanged;
 *   2. every generator commutes with P and ±P is in the group: the outcome is fixed by the signs; nothing changes;
 *   3. every generator commutes with P but ±P is not in the group (P is a logical operator when the group is a code): the outcome is a fair coin
 *      and (−1)^outcome · P joins the group, so a code loses one logical qubit (k → k − 1).
 * Pure TypeScript; the random outcome is an argument, never drawn here. Outcome bit 0 means +1, bit 1 means −1.
 */
import { Pauli, type Letter } from './pauli'
import { GF2Matrix } from './gf2'

export type UpdateCase = 'replaced' | 'fixed' | 'added'

export interface UpdateResult {
  /** Which of the three cases happened. */
  kind: UpdateCase
  /** true when the outcome was already decided by the state (case 2). */
  fixed: boolean
  /** The outcome bit (0 → +1, 1 → −1): the argument when the coin is fair, the forced value when fixed. */
  outcome: 0 | 1
  /** Indices (into the BEFORE list) of the generators that anticommute with P, in order. */
  clashing: number[]
  /** The index of the generator replaced by ±P (case 1), else null. */
  replaced: number | null
  /** Indices whose generator was multiplied by the replaced one (case 1). */
  multiplied: number[]
  before: Pauli[]
  after: Pauli[]
  /** Stored qubits before and after: n − (number of generators). */
  kBefore: number
  kAfter: number
}

const asBits = (p: Pauli): number[] => [...p.x, ...p.z]

/** Does ±P lie in the group generated by `gens`? If so, the sign relating the product of generators to P (outcome bit of P). Pure GF(2) linear algebra on (x | z), then an exact signed product. */
function memberWithSign(gens: readonly Pauli[], P: Pauli): { member: boolean; outcome: 0 | 1 } {
  if (gens.length === 0) return { member: P.weight() === 0, outcome: P.phase === 2 ? 1 : 0 }
  const rows = gens.map(asBits)
  const M = GF2Matrix.fromRows(rows)
  const coeffs = M.transpose().solve(asBits(P))
  if (!coeffs) return { member: false, outcome: 0 }
  let acc = Pauli.identity(P.n)
  coeffs.forEach((c, i) => {
    if (c) acc = acc.mul(gens[i])
  })
  // acc = s · P with s = ±1: P|ψ⟩ = s · acc|ψ⟩ = s|ψ⟩, so the outcome bit is 1 exactly when acc and P carry opposite signs
  return { member: true, outcome: ((acc.phase - P.phase + 4) % 4 === 2 ? 1 : 0) as 0 | 1 }
}

/** Apply the update rule. `outcome` is used only when the coin is fair. `gens` must be independent, commuting and Hermitian; `P` Hermitian. */
export function updateRule(gens: readonly Pauli[], P: Pauli, outcome: 0 | 1 = 0): UpdateResult {
  const n = P.n
  if (!P.isHermitian()) throw new Error('updateRule: P must be Hermitian (a sign, not ±i)')
  for (const g of gens) if (g.n !== n) throw new Error('updateRule: every generator needs the same number of qubits as P')
  const before = gens.map((g) => g)
  const clashing = before.flatMap((g, i) => (g.commutesWith(P) ? [] : [i]))
  const kBefore = n - before.length
  if (clashing.length > 0) {
    const p = clashing[0]
    const after = before.map((g, i) => (i === p ? (outcome ? P.negate() : P) : clashing.includes(i) ? g.mul(before[p]) : g))
    return { kind: 'replaced', fixed: false, outcome, clashing, replaced: p, multiplied: clashing.slice(1), before, after, kBefore, kAfter: kBefore }
  }
  const m = memberWithSign(before, P)
  if (m.member) return { kind: 'fixed', fixed: true, outcome: m.outcome, clashing, replaced: null, multiplied: [], before, after: before, kBefore, kAfter: kBefore }
  return { kind: 'added', fixed: false, outcome, clashing, replaced: null, multiplied: [], before, after: [...before, outcome ? P.negate() : P], kBefore, kAfter: kBefore - 1 }
}

export interface Census {
  /** Non-identity Paulis, 4ⁿ − 1. */
  total: number
  /** ±P in the group: the outcome is already decided. */
  fixed: number
  /** Commute with every generator but are not in the group (logical operators of a code): a fair coin that costs a stored qubit. */
  logical: number
  /** Anticommute with some generator: a fair coin that swaps a generator. */
  clashing: number
}

/** Count the non-identity n-qubit Paulis (n ≤ 4) by what measuring them does to the group. */
export function census(gens: readonly Pauli[], n: number): Census {
  if (!Number.isInteger(n) || n < 1 || n > 4) throw new Error('census: n must be 1 … 4')
  const letters: Letter[] = ['I', 'X', 'Y', 'Z']
  let fixed = 0
  let logical = 0
  let clashing = 0
  const total = 4 ** n - 1
  for (let idx = 1; idx <= total; idx++) {
    const ls: Letter[] = []
    for (let j = 0, v = idx; j < n; j++, v = Math.floor(v / 4)) ls.push(letters[v % 4])
    const P = Pauli.fromLetters(ls)
    if (gens.some((g) => !g.commutesWith(P))) clashing++
    else if (memberWithSign(gens, P).member) fixed++
    else logical++
  }
  return { total, fixed, logical, clashing }
}
