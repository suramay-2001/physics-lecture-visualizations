/* ------------------------------------------------------------------ classical linear codes ------------------------------------------------------------------ */

const toBits = (w: string): number[] => {
  if (!/^[01]+$/.test(w)) throw new Error(`linear code: "${w}" is not a string of 0s and 1s`)
  return [...w].map(Number)
}
const text = (v: Bits): string => v.join('')

/** A binary [n, k] linear code: the span of k independent basic words (the columns of the generator matrix G). */
export class LinearCode {
  readonly n: number
  readonly k: number
  /** the basic words, as rows (so this is Gᵀ) */
  readonly basic: GF2Matrix

  constructor(basicWords: readonly string[]) {
    if (basicWords.length === 0) throw new Error('LinearCode: needs at least one basic word')
    const rows = basicWords.map(toBits)
    const n = rows[0].length
    if (rows.some((r) => r.length !== n)) throw new Error('LinearCode: the basic words differ in length')
    this.basic = GF2Matrix.fromRows(rows, n)
    this.n = n
    this.k = this.basic.rank()
    if (this.k !== rows.length) throw new Error('LinearCode: the basic words are not independent over GF(2)')
  }

  /** The generator matrix G (n × k): its columns are the basic words. */
  generator(): GF2Matrix {
    return this.basic.transpose()
  }

  /** Every code word, as strings, in increasing order of their value as binary numbers (place 1 the most significant bit). */
  words(): string[] {
    const out: string[] = []
    for (let m = 0; m < 2 ** this.k; m++) {
      let v: number[] = new Array<number>(this.n).fill(0)
      for (let i = 0; i < this.k; i++) if (m & (1 << i)) v = xorBits(v, this.basic.rowBits(i))
      out.push(text(v))
    }
    return out.sort()
  }

  /** The number of code words of each weight 0 … n. */
  weightEnumerator(): number[] {
    const e = new Array<number>(this.n + 1).fill(0)
    for (const w of this.words()) e[weight(toBits(w))]++
    return e
  }

  /** The least weight of a nonzero code word (= the least distance between two words, as x + y is a word). */
  distance(): number {
    const e = this.weightEnumerator()
    for (let w = 1; w <= this.n; w++) if (e[w] > 0) return w
    throw new Error('LinearCode: the code has no nonzero word')
  }

  /** k / n. */
  get rate(): number {
    return this.k / this.n
  }

  /** A check matrix M ((n − k) × n, independent rows) with M G = 0 and C = ker M. */
  checkMatrix(): GF2Matrix {
    return this.basic.nullspace()
  }

  /** The dual code C⊥ = { y : y·x = 0 for every x in C }, generated by the rows of M. */
  dual(): LinearCode {
    return new LinearCode(this.checkMatrix().toRows().map(text))
  }

  contains(word: string): boolean {
    return this.basic.rowspaceContains(toBits(word))
  }

  /** M w, as a string of 0/1 (zero exactly for a code word). */
  syndrome(word: string): string {
    return text(this.checkMatrix().mulVec(toBits(word)))
  }
}

/** The code with these basic words (the columns of G, written as strings). */
export const linearCode = (basicWords: readonly string[]): LinearCode => new LinearCode(basicWords)

/** The code ker M of these checks (rows of M, written as strings; they must be independent). */
export function linearCodeFromChecks(checks: readonly string[]): LinearCode {
  const M = GF2Matrix.fromRows(checks.map(toBits), checks[0].length)
  if (M.rank() !== checks.length) throw new Error('linearCodeFromChecks: the checks are not independent over GF(2)')
  return new LinearCode(M.nullspace().toRows().map(text))
}

/** The columns of the check matrix as strings: the syndrome of a single flip at each place 1 … n. */
export function singleFlipSyndromes(checks: readonly string[]): string[] {
  const M = GF2Matrix.fromRows(checks.map(toBits), checks[0].length)
  return Array.from({ length: M.cols }, (_, j) => text(M.colBits(j)))
}

/**
 * Decode with the single-flip table: the received word's syndrome is compared with each place's column; the first place whose column equals it is flipped. A zero
 * syndrome flips nothing, and a syndrome no single flip makes returns `place: null`.
 */
export function decodeSingleFlip(checks: readonly string[], received: string): { syndrome: string; place: number | null; word: string } {
  const M = GF2Matrix.fromRows(checks.map(toBits), checks[0].length)
  const r = toBits(received)
  const s = text(M.mulVec(r))
  if (!s.includes('1')) return { syndrome: s, place: null, word: received }
  const cols = singleFlipSyndromes(checks)
  const j = cols.indexOf(s)
  if (j < 0) return { syndrome: s, place: null, word: received }
  const fixed = r.slice()
  fixed[j] ^= 1
  return { syndrome: s, place: j + 1, word: text(fixed) }
}

/* ------------------------------------------------------------------ coset states of a CSS code (Bergou Eqs. 9.41-9.43) ------------------------------------------------------------------ */

export interface BitAmp {
  bits: string
  amp: number
}

/** |x + C₂⟩ = |C₂|^{-1/2} Σ_{y∈C₂} |x + y⟩ (Bergou Eq. 9.41): real amplitudes, sorted by the bit string. */
export function cosetState(C2: LinearCode, x: string): BitAmp[] {
  const xv = toBits(x)
  if (xv.length !== C2.n) throw new Error('cosetState: x and the code differ in length')
  const a = 1 / Math.sqrt(2 ** C2.k)
  return C2.words()
    .map((y) => ({ bits: text(xorBits(xv, toBits(y))), amp: a }))
    .sort((p, q) => (p.bits < q.bits ? -1 : 1))
}

/** H^{⊗n} applied to a real state: amplitude(u) = 2^{-n/2} Σ_y a_y (-1)^{y·u} (the zero entries are dropped). n ≤ 12. */
export function hadamardImage(state: readonly BitAmp[]): BitAmp[] {
  const n = state[0].bits.length
  if (n > 12) throw new Error('hadamardImage: n is capped at 12')
  const out: BitAmp[] = []
  const norm = 1 / Math.sqrt(2 ** n)
  for (let u = 0; u < 2 ** n; u++) {
    const ub = toBits(u.toString(2).padStart(n, '0'))
    let s = 0
    for (const { bits, amp } of state) s += (dot(toBits(bits), ub) ? -1 : 1) * amp
    if (Math.abs(s * norm) > 1e-12) out.push({ bits: text(ub), amp: s * norm })
  }
  return out
}

/* ------------------------------------------------------------------ Clifford conjugation ------------------------------------------------------------------ */

export interface Conjugated {
  /** true when U P U† is ± a Pauli string */
  clifford: boolean
  /** ±1 when `clifford`, else 0 */
  sign: 1 | -1 | 0
  /** the Pauli string when `clifford`, else null */
  pauli: string | null
  /** U P U† = Σ coefficient · string, every string whose coefficient is not zero (a Clifford has exactly one, ±1) */
  expansion: { pauli: string; re: number; im: number }[]
}

/** U P U† for an n-qubit unitary (n ≤ 3) and a Pauli string, with its expansion in Pauli strings: tr(Q U P U†)/2ⁿ for every string Q. */
export function cliffordConjugate(U: Mat, pauli: string): Conjugated {
  const n = pauli.length
  if (U.length !== 2 ** n) throw new Error(`cliffordConjugate: U is not a ${n}-qubit operator`)
  if (n > 3) throw new Error('cliffordConjugate: at most 3 qubits')
  const M = matmul(matmul(U, pauliString(pauli)), dagger(U))
  const N = 2 ** n
  const expansion: Conjugated['expansion'] = []
  for (const q of pauliStrings(n)) {
    const Q = pauliString(q)
    let tr: C = ZERO
    for (let i = 0; i < N; i++) for (let k = 0; k < N; k++) tr = add(tr, mul(Q[i][k], M[k][i]))
    const lam = scale(tr, 1 / N)
    if (abs2(lam) > 1e-18) expansion.push({ pauli: q, re: lam.re, im: lam.im })
  }
  const only = expansion.length === 1 && Math.abs(expansion[0].im) < 1e-9 && Math.abs(Math.abs(expansion[0].re) - 1) < 1e-9
  return only
    ? { clifford: true, sign: expansion[0].re > 0 ? 1 : -1, pauli: expansion[0].pauli, expansion }
    : { clifford: false, sign: 0, pauli: null, expansion }
}

const key2 = (U: Mat): string => {
  // a 2 × 2 unitary up to a global phase: divide by the phase of its first entry of size > 0.1, round, print
  let ph = c(1)
  outer: for (const row of U)
    for (const z of row)
      if (abs2(z) > 0.01) {
        const m = Math.sqrt(abs2(z))
        ph = c(z.re / m, -z.im / m)
        break outer
      }
  const r = (x: number): string => (Math.round(x * 1e6) / 1e6 + 0).toFixed(6)
  return U.map((row) => row.map((z) => { const w = mul(z, ph); return `${r(w.re)},${r(w.im)}` }).join(';')).join('|')
}

/** The one-qubit Clifford group up to a global phase, found by closing {H, S} under products: its size (24) and one word in H and S for each element. */
export function cliffordClosure(n: 1 = 1): { size: number; words: string[] } {
  if (n !== 1) throw new Error('cliffordClosure: only n = 1')
  const gens: [string, Mat][] = [['H', H], ['S', S]]
  const seen = new Map<string, string>()
  const id: Mat = [[c(1), c(0)], [c(0), c(1)]]
  seen.set(key2(id), '')
  let frontier: [string, Mat][] = [['', id]]
  while (frontier.length) {
    const next: [string, Mat][] = []
    for (const [w, U] of frontier)
      for (const [g, G] of gens) {
        const V = matmul(G, U)
        const k = key2(V)
        if (!seen.has(k)) {
          seen.set(k, g + w)
          next.push([g + w, V])
        }
      }
    frontier = next
  }
  return { size: seen.size, words: [...seen.values()] }
}

