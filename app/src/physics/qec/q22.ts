/* ------------------------------------------------------------------ the tableau followed through a circuit ------------------------------------------------------------------ */

export interface TableauTrace {
  n: number
  /** signed generators (e.g. "+ZZI") before the first column, then after every column */
  steps: string[][]
  /** the outcomes used, in order of measurement */
  outcomes: string
}

const CLIFF_1Q = new Set(['H', 'S', 'Sdg', 'X', 'Y', 'Z'])

/**
 * Follow a stabilizer circuit with the Gottesman-Knill tableau: signed generators before the circuit and after each column. Gates H, S, S†, X, Y, Z, CNOT
 * (X with one control), CZ (Z with one control) and SWAP; Z measurements take their outcome from `outcomes` (one character per measurement, in order; a
 * measurement the state already fixes ignores it); a gate with `cond` runs only when the recorded bits read as it says. `init` characters other than 0 and 1
 * (+, -) are not supported. Any other gate (T, a rotation) throws: it is not Clifford.
 */
export function tableauTrace(circuit: Circuit, outcomes = ''): TableauTrace {
  const n = circuit.qubits
  const t = new Tableau(n)
  const init = circuit.init ?? '0'.repeat(n)
  for (let q = 0; q < n; q++) {
    if (init[q] === '1') t.px(q)
    else if (init[q] !== '0') throw new Error('tableauTrace: init must be 0s and 1s')
  }
  const bits: Record<number, number> = {}
  let used = ''
  const show = (): string[] => t.stabilizers().map((p) => p.toString())
  const steps: string[][] = [show()]
  for (const col of circuit.columns) {
    for (const op of col as Op[]) {
      if (op.op === 'measure') {
        const want = outcomes[used.length]
        const r = t.measureZ(op.qubit, want === '1' ? 1 : 0)
        bits[op.bit] = r.outcome
        used += String(r.outcome)
        continue
      }
      if (op.op !== 'gate') throw new Error('tableauTrace: only gates and measurements')
      if (op.cond && !op.cond.bits.every((b, i) => bits[b] === Number(op.cond!.equals[i]))) continue
      const ctl = op.controls ?? []
      if (ctl.length === 0 && op.gate === 'SWAP') t.swap(op.targets[0], op.targets[1])
      else if (ctl.length === 0 && CLIFF_1Q.has(op.gate)) t.apply(op.gate as 'H' | 'S' | 'Sdg' | 'X' | 'Y' | 'Z', op.targets[0])
      else if (ctl.length === 1 && op.gate === 'X') t.cnot(ctl[0], op.targets[0])
      else if (ctl.length === 1 && op.gate === 'Z') t.cz(ctl[0], op.targets[0])
      else throw new Error(`tableauTrace: ${op.gate} is not a Clifford gate the tableau runs`)
    }
    steps.push(show())
  }
  return { n, steps, outcomes: used }
}

/** Do these two lists of signed Pauli strings generate the same stabilizer group (same elements with the same signs)? */
export function sameStabilizerGroup(a: readonly string[], b: readonly string[]): boolean {
  const A = a.map((s) => Pauli.parse(s))
  const B = b.map((s) => Pauli.parse(s))
  if (A.length !== B.length) return false
  const inGroup = (gens: Pauli[], p: Pauli): boolean => {
    // p is a product of the generators with the right sign: test through the stabilizer code's membership
    const code = new StabilizerCode(gens)
    return code.membership(p) === 'in'
  }
  return A.every((p) => inGroup(B, p)) && B.every((p) => inGroup(A, p))
}

/* ------------------------------------------------------------------ the pseudo-threshold ------------------------------------------------------------------ */

/**
 * The positive p* at which a CSS code's logical failure chance against independent flips of one kind equals the bare qubit's p: P_L(p) = p, found by bisection on
 * (0, 1/2) (P_L(p) < p below it, P_L(p) > p above it). Exact enumeration underneath (rates.ts, n ≤ 16).
 */
export function pseudoThreshold(code: CSSCode, kind: 'X' | 'Z' = 'X'): number {
  const f = (p: number): number => logicalFailure(code, p, kind) - p
  // P_L(p) = p again at p = 1/2 (a uniformly random pattern), so bracket the FIRST crossing by stepping up from a small p until the code starts to hurt
  let lo = 1e-3
  if (!(f(lo) < 0)) throw new Error('pseudoThreshold: the code does not help at p = 0.001')
  let hi = lo
  while (f(hi) <= 0) {
    lo = hi
    hi += 1e-3
    if (hi >= 0.5) throw new Error('pseudoThreshold: no crossing below 1/2')
  }
  for (let i = 0; i < 80; i++) {
    const mid = (lo + hi) / 2
    if (f(mid) < 0) lo = mid
    else hi = mid
  }
  return (lo + hi) / 2
}
